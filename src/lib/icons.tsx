function googleIcon(symbol: string): LucideIcon {
  const Icon: LucideIcon = ({ size = 20, strokeWidth, fill, color, style, ...props }) => {
    void strokeWidth;
    return (
      <MaterialIcon
        {...props}
        name={symbol}
        size={size}
        filled={fill === "currentColor"}
        style={{ color, ...style }}
      />
    );
  };
  Icon.displayName = `GoogleIcon(${symbol})`;
  return Icon;
}

